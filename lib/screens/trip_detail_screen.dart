/// Full-page trip report.
class TripDetailScreen extends StatelessWidget {
  const TripDetailScreen({
    super.key,
    required this.trip,
    required this.onDelete,
  });

  final Map<String, dynamic> trip;

  /// Deletes the trip; the page closes when it completes.
  final Future<void> Function() onDelete;

  /// The PDF is in English: its built-in fonts have no Arabic letters.
  static String _pdfLabel(TripEventKind kind) => switch (kind) {
    TripEventKind.drowsy => 'Drowsiness detected',
    TripEventKind.distracted => 'Distraction detected',
    TripEventKind.danger => 'Eyes closed: danger alert',
    TripEventKind.sos => 'SOS sent',
    _ => 'Event',
  };

  List<String> _pdfEventLines() {
    final lines = <String>[];
    for (final e in TripRecords.events(trip)) {
      if (e.kind == TripEventKind.started ||
          e.kind == TripEventKind.ended ||
          e.isResponse) {
        continue;
      }
      final time = e.time == null
          ? '--:--'
          : intl.DateFormat('HH:mm').format(e.time!);
      lines.add('$time - ${_pdfLabel(e.kind)}');
    }
    return lines;
  }

  Future<void> _generateAndSharePdf(Rect? shareButton) async {
    final start = TripRecords.startedAt(trip);
    final date = intl.DateFormat(
      'EEEE d MMM yyyy, HH:mm',
    ).format(start ?? TripRecords.date(trip));
    final events = _pdfEventLines();

    final pdf = pw.Document();
    // A long trip can log more events than fit on one page.
    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        footer: (context) => pw.Text("Generated by Yaqdah App"),
        build: (pw.Context context) => [
          pw.Header(
            level: 0,
            child: pw.Text(
              "Trip Report - Yaqdah",
              style: pw.TextStyle(fontSize: 24, fontWeight: pw.FontWeight.bold),
            ),
          ),
          pw.SizedBox(height: 20),
          pw.Text("Date: $date"),
          pw.Text("Duration: ${trip['duration']}"),
          pw.Text("Distance: ${trip['distance']}"),
          pw.Text("Status: ${trip['status']}"),
          pw.Text("Safety score: ${trip['score'] ?? 100}"),
          pw.Divider(),
          pw.Text(
            "Alerts Log:",
            style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 10),
          if (events.isEmpty) pw.Text("No alerts on this trip."),
          for (final line in events) pw.Bullet(text: line),
        ],
      ),
    );
    await Printing.sharePdf(
      bytes: await pdf.save(),
      filename: 'trip_report_${trip['id']}.pdf',
      // iPad shows the share sheet as a popover from this button.
      bounds: shareButton,
    );
  }

  Future<void> _confirmDelete(BuildContext context) async {
    final l10n = AppLocalizations.of(context)!;
    final c = AppColors.of(context);
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: Text(l10n.deleteTripConfirmTitle),
        content: Text(l10n.deleteTripConfirmBody),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx, false),
            style: TextButton.styleFrom(foregroundColor: c.subtext),
            child: Text(l10n.cancel),
          ),
          TextButton(
            onPressed: () => Navigator.pop(ctx, true),
            style: TextButton.styleFrom(foregroundColor: c.danger),
            child: Text(l10n.delete),
          ),
        ],
      ),
    );
    if (confirmed != true) return;
    await onDelete();
    if (context.mounted) Navigator.pop(context);
  }

  @override
  Widget build(BuildContext context) {
    final c = AppColors.of(context);
    final l10n = AppLocalizations.of(context)!;

    final alerts = TripRecords.countAlerts(trip['alerts']);
    final isSafe = TripRecords.isSafe(trip, alerts: alerts);
    final date = TripRecords.date(trip);
    final start = TripRecords.clockLabel(
      TripRecords.startedAt(trip),
      l10n.localeName,
    );
    final end = TripRecords.clockLabel(
      TripRecords.endedAt(trip),
      l10n.localeName,
    );
    final avg = TripRecords.speed(trip['avgSpeed']);
    final top = TripRecords.speed(trip['maxSpeed']);
    final score = trip['score'] ?? 100;

    return Scaffold(
      appBar: AppBar(
        leading: IconButton(
          onPressed: () => Navigator.pop(context),
          tooltip: MaterialLocalizations.of(context).backButtonTooltip,
          icon: AppIcon(
            Symbols.arrow_back_rounded,
            color: c.text,
            mirror: true,
          ),
        ),
        title: Text(l10n.tripDetailsTitle),
        actions: [
          Builder(
            builder: (buttonContext) => IconButton(
              onPressed: () {
                final box = buttonContext.findRenderObject() as RenderBox?;
                _generateAndSharePdf(
                  box == null
                      ? null
                      : box.localToGlobal(Offset.zero) & box.size,
                );
              },
              tooltip: l10n.shareReport,
              icon: AppIcon(Symbols.ios_share_rounded, size: 22, color: c.text),
            ),
          ),
          const SizedBox(width: 4),
        ],
      ),
      body: SafeArea(
        top: false,
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Expanded(
              child: ListView(
                padding: const EdgeInsets.fromLTRB(20, 8, 20, 16),
                children: [
                  _RouteMap(tripId: trip['id'] as int),
                  const SizedBox(height: 14),
                  Padding(
                    padding: const EdgeInsets.symmetric(horizontal: 4),
                    child: Row(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Expanded(
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              Text(
                                intl.DateFormat(
                                  'EEEE, d MMM',
                                  l10n.localeName,
                                ).format(date),
                                style: AppFonts.display(
                                  context,
                                  24,
                                  color: c.text,
                                  tracking: -0.01,
                                ),
                              ),
                              const SizedBox(height: 4),
                              if (start.isNotEmpty)
                                Text(
                                  end.isEmpty ? start : '$start – $end',
                                  style: AppFonts.body(
                                    context,
                                    15,
                                    color: c.subtext,
                                  ),
                                ),
                            ],
                          ),
                        ),
                        const SizedBox(width: 12),
                        _StatusPill(
                          safe: isSafe,
                          label: isSafe
                              ? l10n.tripSafe
                              : l10n.alertCount(alerts),
                        ),
                      ],
                    ),
                  ),
                  const SizedBox(height: 14),
                  AppCard(
                    radius: 22,
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.stretch,
                      children: [
                        Row(
                          children: [
                            Expanded(
                              child: Text(
                                l10n.safetyScore,
                                style: AppFonts.body(
                                  context,
                                  15,
                                  weight: FontWeight.w600,
                                  color: c.subtext,
                                ),
                              ),
                            ),
                            Text.rich(
                              TextSpan(
                                text: '$score',
                                style: AppFonts.display(
                                  context,
                                  30,
                                  color: c.text,
                                ),
                                children: [
                                  TextSpan(
                                    text: ' / 100',
                                    style: AppFonts.body(
                                      context,
                                      15,
                                      weight: FontWeight.w500,
                                      color: c.subtext,
                                    ),
                                  ),
                                ],
                              ),
                            ),
                          ],
                        ),
                        const SizedBox(height: 14),
                        Divider(color: c.line),
                        const SizedBox(height: 14),
                        Row(
                          children: [
                            _GridStat(
                              value: trip['duration']?.toString() ?? '0:00:00',
                              label: l10n.tripDuration,
                            ),
                            _GridStat(
                              value:
                                  '${TripRecords.distanceKm(trip).toStringAsFixed(1)} ${l10n.kmUnit}',
                              label: l10n.tripDistance,
                            ),
                          ],
                        ),
                        const SizedBox(height: 14),
                        Row(
                          children: [
                            _GridStat(
                              value: avg == null
                                  ? '—'
                                  : '${avg.round()} ${l10n.kmhUnit}',
                              label: l10n.avgSpeed,
                            ),
                            _GridStat(
                              value: top == null
                                  ? '—'
                                  : '${top.round()} ${l10n.kmhUnit}',
                              label: l10n.topSpeed,
                            ),
                          ],
                        ),
                      ],
                    ),
                  ),
                  const SizedBox(height: 14),
                  _Timeline(trip: trip),
                ],
              ),
            ),
            Padding(
              padding: const EdgeInsets.fromLTRB(20, 8, 20, 16),
              child: SizedBox(
                height: 52,
                child: Material(
                  color: c.dangerSoft,
                  borderRadius: BorderRadius.circular(16),
                  clipBehavior: Clip.antiAlias,
                  child: InkWell(
                    onTap: () => _confirmDelete(context),
                    child: Row(
                      mainAxisAlignment: MainAxisAlignment.center,
                      children: [
                        AppIcon(
                          Symbols.delete_rounded,
                          size: 20,
                          color: c.danger,
                        ),
                        const SizedBox(width: 8),
                        Text(
                          l10n.deleteTrip,
                          style: AppFonts.body(
                            context,
                            16,
                            weight: FontWeight.w700,
                            color: c.danger,
                          ),
                        ),
                      ],
                    ),
                  ),
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

/// The recorded route, read from the database when the page opens (trip
/// lists leave routes out: they can be large).
class _RouteMap extends StatefulWidget {
  const _RouteMap({required this.tripId});

  final int tripId;

  @override
  State<_RouteMap> createState() => _RouteMapState();
}

class _RouteMapState extends State<_RouteMap> {
  late final Future<List<LatLng>> _route = _load();

  Future<List<LatLng>> _load() async {
    final raw = await DatabaseService.instance.getTripRoute(widget.tripId);
    if (raw == null || raw.length < 3) return const [];
    // An hour's drive is thousands of points: decode off the UI thread.
    return raw.length > 20000 ? compute(_decodeRoute, raw) : _decodeRoute(raw);
  }

  @override
  Widget build(BuildContext context) {
    final c = AppColors.of(context);
    final l10n = AppLocalizations.of(context)!;

    return Container(
      height: 130,
      clipBehavior: Clip.antiAlias,
      decoration: BoxDecoration(
        color: c.surface2,
        borderRadius: BorderRadius.circular(22),
        border: Border.all(color: c.line),
      ),
      child: FutureBuilder<List<LatLng>>(
        future: _route,
        builder: (context, snapshot) {
          if (snapshot.connectionState != ConnectionState.done) {
            return const SizedBox.shrink();
          }
          return _buildMap(context, snapshot.data ?? const [], c, l10n);
        },
      ),
    );
  }

  Widget _buildMap(
    BuildContext context,
    List<LatLng> points,
    AppColors c,
    AppLocalizations l10n,
  ) {
    return points.isEmpty
        ? Center(
            child: Row(
              mainAxisSize: MainAxisSize.min,
              children: [
                AppIcon(Symbols.route_rounded, size: 20, color: c.subtext),
                const SizedBox(width: 8),
                Text(
                  l10n.noRouteRecorded,
                  style: AppFonts.body(context, 14, color: c.subtext),
                ),
              ],
            ),
          )
        : FlutterMap(
            options: MapOptions(
              backgroundColor: c.surface2,
              initialCameraFit: points.length > 1
                  ? CameraFit.coordinates(
                      coordinates: points,
                      padding: const EdgeInsets.all(24),
                      maxZoom: 16,
                    )
                  : null,
              initialCenter: points.first,
              initialZoom: 14,
              interactionOptions: const InteractionOptions(
                flags: InteractiveFlag.none,
              ),
            ),
            children: [
              TileLayer(
                urlTemplate: mapboxTileUrl(context),
                userAgentPackageName: 'com.example.yaqdah_app',
              ),
              PolylineLayer(
                polylines: [
                  Polyline(points: points, strokeWidth: 4, color: c.primary),
                ],
              ),
              MarkerLayer(
                markers: [
                  Marker(
                    point: points.first,
                    width: 14,
                    height: 14,
                    child: _Dot(color: c.primary),
                  ),
                  Marker(
                    point: points.last,
                    width: 14,
                    height: 14,
                    child: _Dot(color: c.text),
                  ),
                ],
              ),
            ],
          );
  }
}

List<LatLng> _decodeRoute(String raw) {
  try {
    final list = json.decode(raw);
    if (list is! List) return const [];
    return [
      for (final item in list)
        if (item is Map && item['lat'] is num && item['lng'] is num)
          LatLng(
            (item['lat'] as num).toDouble(),
            (item['lng'] as num).toDouble(),
          ),
    ];
  } catch (e) {
    return const [];
  }
}

