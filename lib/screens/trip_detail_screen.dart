class _TimelineItem {
  const _TimelineItem({
    required this.title,
    required this.subtitle,
    required this.dot,
    this.titleColor,
  });

  final String title;
  final String subtitle;
  final Color dot;
  final Color? titleColor;
}

/// Trip events as dots joined by a 2px line. Driver responses are folded
/// into the alert they answered ("8:47 PM · you took a break").
class _Timeline extends StatelessWidget {
  const _Timeline({required this.trip});

  final Map<String, dynamic> trip;

  @override
  Widget build(BuildContext context) {
    final c = AppColors.of(context);
    final l10n = AppLocalizations.of(context)!;
    final timeFormat = intl.DateFormat.jm(l10n.localeName);
    final events = TripRecords.events(trip);

    final items = <_TimelineItem>[];
    for (var i = 0; i < events.length; i++) {
      final e = events[i];
      if (e.isResponse || e.kind == TripEventKind.other) continue;
      final time = e.time == null ? '' : timeFormat.format(e.time!);

      String? response;
      if (i + 1 < events.length && events[i + 1].isResponse) {
        response = switch (events[i + 1].kind) {
          TripEventKind.tookBreak => l10n.tlTookBreak,
          TripEventKind.keptDriving => l10n.tlKeptDriving,
          _ => l10n.tlConfirmedAwake,
        };
      }
      final subtitle = response == null ? time : '$time · $response';

      switch (e.kind) {
        case TripEventKind.started:
          items.add(
            _TimelineItem(
              title: l10n.tlTripStarted,
              subtitle: subtitle,
              dot: c.primary,
            ),
          );
        case TripEventKind.ended:
          items.add(
            _TimelineItem(
              title: l10n.tlTripEnded,
              subtitle: subtitle,
              dot: c.subtext,
            ),
          );
        case TripEventKind.drowsy:
          items.add(
            _TimelineItem(
              title: l10n.tlDrowsy,
              subtitle: subtitle,
              dot: c.warn,
              titleColor: c.warn,
            ),
          );
        case TripEventKind.distracted:
          items.add(
            _TimelineItem(
              title: l10n.tlDistracted,
              subtitle: subtitle,
              dot: c.warn,
              titleColor: c.warn,
            ),
          );
        case TripEventKind.danger:
          items.add(
            _TimelineItem(
              title: l10n.tlDanger,
              subtitle: subtitle,
              dot: c.danger,
              titleColor: c.danger,
            ),
          );
        case TripEventKind.sos:
          items.add(
            _TimelineItem(
              title: l10n.tlSos,
              subtitle: subtitle,
              dot: c.danger,
              titleColor: c.danger,
            ),
          );
        default:
          break;
      }
    }

    if (items.isEmpty) return const SizedBox.shrink();

    return Padding(
      padding: const EdgeInsets.symmetric(horizontal: 4),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Text(
            l10n.timeline,
            style: AppFonts.body(
              context,
              17,
              weight: FontWeight.w700,
              color: c.text,
            ),
          ),
          const SizedBox(height: 12),
          for (var i = 0; i < items.length; i++)
            IntrinsicHeight(
              child: Row(
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: [
                  Column(
                    children: [
                      Container(
                        width: 12,
                        height: 12,
                        margin: const EdgeInsets.only(top: 4),
                        decoration: BoxDecoration(
                          color: items[i].dot,
                          shape: BoxShape.circle,
                        ),
                      ),
                      if (i < items.length - 1)
                        Expanded(child: Container(width: 2, color: c.line)),
                    ],
                  ),
                  const SizedBox(width: 14),
                  Expanded(
                    child: Padding(
                      padding: EdgeInsets.only(
                        bottom: i < items.length - 1 ? 16 : 0,
                      ),
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text(
                            items[i].title,
                            style: AppFonts.body(
                              context,
                              15,
                              weight: FontWeight.w600,
                              color: items[i].titleColor ?? c.text,
                            ),
                          ),
                          const SizedBox(height: 2),
                          Text(
                            items[i].subtitle,
                            style: AppFonts.body(context, 14, color: c.subtext),
                          ),
                        ],
                      ),
                    ),
                  ),
                ],
              ),
            ),
        ],
      ),
    );
  }
}
